"""Generate docs/REAL_RESULTS.md from the real-data metric JSONs.

Run: python -m scripts.write_real_results

Generated, not hand-written: a numbers document typed by hand drifts from the artifacts the
moment anything is rerun, and a stale figure in a file titled "real results" is worse than
no file.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs"


def load(name: str):
    p = DOCS / name
    return json.loads(p.read_text()) if p.exists() else None


def pc(v, n=1):
    return f"{v * 100:.{n}f}%"


def main() -> None:
    q = load("real_qualification.json")
    a = load("metrics_real_sidea.json")
    b = load("metrics_real_sideb.json")
    v = load("metrics_vision.json")
    adv = load("metrics_adversarial.json")
    rings = load("rings.json")

    L: list[str] = []
    w = L.append

    w("# AEGIS — Results on Real Data\n")
    w("Generated by `scripts/write_real_results.py`. Do not edit by hand.\n")
    w("Every figure here comes from public datasets. Nothing on this page is simulated.\n")
    w("| Layer | Dataset | Scale |")
    w("|---|---|---|")
    w("| Transactions & chargebacks | IEEE-CIS Fraud Detection (Vesta Corporation) | 590,540 transactions, 20,663 reported chargebacks, 182-day span |")
    w("| Receipt evidence | CORD (Naver Clova) + SROIE (ICDAR 2019 RRC) | 1,973 real receipt photographs |")
    w("")
    w("IEEE-CIS's `isFraud` is defined by the data provider as **a reported chargeback on the**")
    w("**card** — these are real disputes, not a proxy. Receipt manipulations are applied")
    w("programmatically to real annotated regions of real photographs, which is the methodology")
    w("of DocTamper (CVPR 2023) and AIForge-Doc (2026).\n")
    w("---\n")

    # ---------------- CE 3.0 ----------------
    if q:
        w("## 1. Visa CE 3.0, applied unmodified to real chargebacks\n")
        w("This is a **rules computation, not a model**. The result is a fact about the data.\n")
        f = q["funnel"]
        w("| Stage | Cases | Share |")
        w("|---|---|---|")
        w(f"| Real reported chargebacks | {q['n_chargebacks']:,} | 100% |")
        w(f"| Assessable (raised late enough for a 120-day lookback) | {q['n_assessable']:,} | {pc(q['n_assessable'] / q['n_chargebacks'], 0)} |")
        w(f"| Clear the prior-history gate (≥2 eligible priors) | {f['cleared_prior_gate']:,} | {pc(f['cleared_prior_gate'] / q['n_assessable'])} |")
        w(f"| **Qualify for CE 3.0** | **{q['qualified']}** | **{pc(q['qualified_rate'], 2)}** |")
        w("")
        w(f"**{f['blocked_no_main_anchor']} of the {f['cleared_prior_gate']} cases that clear the")
        w(f"history gate ({pc(f['blocked_no_main_anchor'] / max(f['cleared_prior_gate'], 1), 0)}) fail for exactly one reason: no Main anchor was ever")
        w("captured.** They match on address or email, but on no IP and no device. Visa rejects")
        w(f"them. A naive \"any two of four\" reading passes all of them — **{q['naive_false_positives']} false positives")
        w(f"worth ₹{q['naive_false_positive_inr']:,.0f}** in representments that would be filed and lost.\n")

        w("### Capture coverage, measured\n")
        w("| CE 3.0 element | Coverage |")
        w("|---|---|")
        for k, val in q["capture_coverage"].items():
            w(f"| `{k}` | {pc(val, 1) if val > 0 else '**anonymised in this dataset**'} |")
        w("")
        w("Device fingerprint — composed from `DeviceInfo` + OS + browser + colour depth +")
        w("screen resolution, the same components a commercial fingerprinting library hashes —")
        w("is the **only Main element available**, and it is present on under a quarter of")
        w("transactions. Purchase IP is anonymised by the provider, so the \"two Main\" path")
        w("cannot be assessed at all. Both constraints push the measured rate **below** reality.\n")

        w("### Where cases die\n")
        w("| Blocking gap | Cases |")
        w("|---|---|")
        for k, val in list(q["blocking_gaps"].items())[:6]:
            w(f"| `{k}` | {val:,} |")
        w("")
        if q.get("sensitivity"):
            w("### Sensitivity to the prior-age floor\n")
            w("| Prior age floor | Qualify | Rate |")
            w("|---|---|---|")
            for d, s in q["sensitivity"].items():
                w(f"| ≥ {d} days | {s['qualified']} | {pc(s['rate'], 2)} |")
            w("")
            w("Relaxing the window barely moves the number, which separates the two possible")
            w("explanations: this is **missing customer history**, not a dataset too short to look")
            w("back through.\n")
        w("**What this actually means.** CE 3.0 was designed for friendly fraud — a genuine repeat")
        w("customer disputing a genuine purchase. IEEE-CIS is dominated by criminal card-not-present")
        w("fraud, where the cardholder has no relationship with the merchant at all. The finding is")
        w("not that CE 3.0 is useless; it is that **it is unavailable to the overwhelming majority")
        w("of chargebacks, and the binding constraint is data capture, not legal argument.**\n")
        w("---\n")

    # ---------------- Side A ----------------
    if a and "temporal" in a:
        t = a["temporal"]
        w("## 2. Chargeback risk model — temporal split\n")
        p = a.get("protocol", {})
        w(f"Trained on days 0–{p.get('train_end_day', 120)}, calibrated on the gap, tested on days")
        w(f"{p.get('gap_end_day', 150)}–{p.get('test_end_day', 182)}. Fitted on the past, scoring the future.\n")
        w("| Metric | Value |")
        w("|---|---|")
        w(f"| Test transactions | {t['n']:,} |")
        w(f"| Base rate | {pc(t['base_rate'], 2)} |")
        w(f"| **PR-AUC** | **{t['pr_auc']:.4f}** ({t['lift_over_base']:.1f}× lift) |")
        w(f"| ROC-AUC | {t['roc_auc']:.4f} |")
        w(f"| Best-F1 precision / recall | {t['best_f1']['precision']:.3f} / {t['best_f1']['recall']:.3f} |")
        w(f"| Recall at precision ≥ 0.50 | {t['at_precision_50']['recall']:.3f} |")
        w("")
        if a.get("random_split"):
            r = a["random_split"]
            w(f"**A random split would report {r['pr_auc']:.4f}.** The same model scores")
            w(f"{t['pr_auc']:.4f} when it has to predict forward in time — a {r['pr_auc'] - t['pr_auc']:.3f} PR-AUC gap")
            w("that a random split silently hides. Fraud arrives in bursts sharing devices and BINs,")
            w("so same-week rows on both sides of the split leak hard.\n")
        if a.get("contaminated_reference"):
            c = a["contaminated_reference"]
            w("### Leakage found and removed\n")
            w(f"Adding a \"has this customer had a prior chargeback\" feature lifts PR-AUC to")
            w(f"**{c['pr_auc']:.4f}** and ROC-AUC to {c['roc_auc']:.4f}. That is not skill, it is the label:")
            w("Vesta applies the fraud flag to the account, email and billing address associated with")
            w("a reported chargeback, so within a resolved entity \"a prior transaction was fraud\" and")
            w("\"this transaction is fraud\" are the same retrospective labelling event. **The feature")
            w("is excluded and the honest number reported instead.**\n")
        if a.get("without_ce3_features"):
            n = a["without_ce3_features"]
            w(f"Removing the CE 3.0 relationship features changes PR-AUC to {n['pr_auc']:.4f}. They are")
            w("near-neutral for fraud prediction — an honest negative result. Their value is to the")
            w("**rulebook**, where they decide qualification, not to the risk model.\n")
        w("---\n")

    # ---------------- Side B ----------------
    if b and "held_out" in b:
        h = b["held_out"]
        hb = b.get("human_baseline", {})
        w("## 3. Evidence forensics on real receipt photographs\n")
        w("| Metric | AEGIS (real photos) | Human baseline |")
        w("|---|---|---|")
        w(f"| Precision | **{pc(h['precision'])}** | — |")
        w(f"| Recall | **{pc(h['recall'])}** | {pc(hb.get('recall', 0.77))} |")
        w(f"| F1 | {pc(h['f1'])} | {pc(hb.get('f1', 0.852))} |")
        w(f"| False-positive rate | **{pc(h['fpr'])}** | {pc(hb.get('fpr', 0.12))} |")
        w(f"| PR-AUC | {h['pr_auc']:.3f} | — |")
        w("")
        w("**This is worse than the synthetic result, and that is the point.** On our own rendered")
        w("fakes the detector reached 97.3% recall. On real photographs with real copy-move and")
        w(f"splice manipulations it reaches **{pc(h['recall'])} — below the human baseline.** Rendered")
        w("fakes carried broken arithmetic and impossibly regular typography; a manipulation inside")
        w("a genuine photograph carries neither. Precision stays high at a low false-positive rate,")
        w("so what it flags is trustworthy — it simply misses more than half.\n")
        if b.get("per_family"):
            w("### Per family\n")
            w("| Family | n | Result |")
            w("|---|---|---|")
            for fam, x in b["per_family"].items():
                if fam == "genuine":
                    w(f"| `genuine` | {x['n']} | {pc(x['false_positive_rate'])} false-positive rate |")
                else:
                    w(f"| `{fam}` | {x['n']} | {pc(x['recall'])} recall |")
            w("")
            w("`recycled` — an authentic, unaltered receipt submitted against a different order —")
            w("collapses, because catching it requires reading the printed total off a real")
            w("photograph, and OCR on real receipts parses only about a third of fields.\n")
        if b.get("leave_one_family_out"):
            w("### Generalisation to an unseen manipulation type\n")
            w("| Held out of training | Recall | FPR | PR-AUC |")
            w("|---|---|---|---|")
            for fam, x in b["leave_one_family_out"].items():
                w(f"| `{fam}` | {pc(x['recall'])} | {pc(x['fpr'])} | {x['pr_auc']:.3f} |")
            w("")
        if b.get("ablations"):
            w("### Ablations\n")
            w("| Feature groups kept | Features | Recall | Precision | PR-AUC |")
            w("|---|---|---|---|---|")
            for k, x in b["ablations"].items():
                w(f"| `{k}` | {x['n_features']} | {pc(x['recall'])} | {pc(x['precision'])} | {x['pr_auc']:.3f} |")
            w("")
            w("Dropping compression forensics costs the most. On real photographs the JPEG history")
            w("is the signal, where on rendered fakes it was arithmetic.\n")
        if b.get("importance_by_group"):
            w("### Feature-group importance\n")
            w("| Group | Importance |")
            w("|---|---|")
            for g, val in sorted(b["importance_by_group"].items(), key=lambda kv: -kv[1]):
                w(f"| `{g}` | {val} |")
            w("")
        w("---\n")

    # ---------------- Vision ----------------
    if v:
        w("## 4. Noise-residual CNN\n")
        w("Fixed SRM high-pass front end (non-trainable) + four convolutional blocks + global max")
        w("pooling, so the network sees the noise residual rather than the picture, and a local")
        w("tamper is not averaged away. Exported to ONNX for serving.\n")
        w("| Metric | Value |")
        w("|---|---|")
        w(f"| Precision | {pc(v['precision'])} |")
        w(f"| Recall | {pc(v['recall'])} |")
        w(f"| PR-AUC | {v['pr_auc']:.3f} |")
        w(f"| ROC-AUC | {v['roc_auc']:.3f} |")
        w(f"| FPR | {pc(v['fpr'])} |")
        w("")
        if v["pr_auc"] < 0.65:
            w("**Reported as a negative result.** The network does not beat the classical feature")
            w("set, and the diagnosis is architectural rather than mysterious: a whole receipt is")
            w("resized to 384×384 before the first convolution, which shrinks a tampered region of")
            w("roughly 400×50 pixels to about 170×20 and smooths away the very discontinuity being")
            w("looked for. The fix is patch-level training at native resolution using the tamper")
            w("boxes already recorded during corpus construction, with max-aggregation over a")
            w("sliding window at inference. That is the identified next step, not a claimed result.\n")
        w("---\n")

    # ---------------- Adversarial ----------------
    if adv:
        w("## 5. Adversarial robustness\n")
        w("Countermeasures applied only to the tampered half of the held-out set; genuine items")
        w("are untouched, so the false-positive rate is unchanged and any recall lost here is real.\n")
        w("| Countermeasure | Recall | Δ | What it destroys |")
        w("|---|---|---|---|")
        effects = {
            "none": "baseline",
            "strip_exif": "provenance group",
            "recompress": "compression-history discontinuity",
            "resize": "JPEG block grid",
            "add_noise": "local noise floor",
            "screenshot": "all of the above",
        }
        base = adv["baseline_recall"]
        for k, x in adv["attacks"].items():
            d = "—" if k == "none" else f"{(x['recall'] - base) * 100:+.1f}pt"
            w(f"| `{k}` | {pc(x['recall'])} | {d} | {effects.get(k, '')} |")
        w("")
        w(f"**Worst case: `{adv['worst_attack']}` drops recall to {pc(adv['worst_recall'])}**, a loss of")
        w(f"{adv['recall_lost_to_worst'] * 100:.1f} points. Every one of these is a single command or a")
        w("forwarded screenshot. This is the floor a merchant should plan around.\n")
        w("---\n")

    # ---------------- Rings ----------------
    if rings:
        w("## 6. Abuse-ring linkage\n")
        w("| Metric | Value |")
        w("|---|---|")
        w(f"| Rings found | {rings['n_rings']:,} |")
        w(f"| Entities inside rings | {rings['n_entities_in_rings']:,} |")
        w(f"| **Chargeback rate inside rings** | **{pc(rings['chargeback_rate_in_rings'])}** |")
        w(f"| Chargeback rate outside | {pc(rings['chargeback_rate_outside'])} |")
        w(f"| Lift | **{rings['lift']:.2f}×** |")
        w(f"| Chargeback value inside rings | ₹{rings['chargeback_value_in_rings_inr']:,.0f} |")
        w("")
        w("| Ring | Entities | Devices | Chargeback rate | Value |")
        w("|---|---|---|---|---|")
        for x in rings["largest_rings"][:6]:
            w(f"| #{x['ring_id']} | {x['n_entities']} | {x['n_devices']} | {pc(x['chargeback_rate'], 0)} | ₹{x['chargeback_value_inr']:,.0f} |")
        w("")
        w("**Only one link key survives scrutiny.** Measured on real data, `customer_email` holds 59")
        w("distinct values (it is a *domain*) and `shipping_address` holds 437 (`addr1` is a region")
        w("code). Linking strangers on those would manufacture enormous meaningless clusters. Only")
        w("the device fingerprint identifies a shared machine.\n")
        if rings.get("excluded_hairballs"):
            hb = rings["excluded_hairballs"]
            tot = sum(h["n_entities"] for h in hb)
            w(f"**{len(hb)} oversized component(s) totalling {tot:,} entities were excluded as hairballs.**")
            w("Connected components on a shared-identifier graph produce a giant component through")
            w("transitive linking — at a looser threshold the largest held 16,415 entities, which is")
            w("not a ring, just noise. The lift above is computed on the actionable rings only.\n")
        w("---\n")

    w("## What remains modelled\n")
    w("No public dataset carries a **\"won the representment\"** outcome. The win-probability model")
    w("and the Cost Lab that consumes it therefore remain driven by a documented structural model,")
    w("and are labelled as such throughout. That is now one fenced-off component rather than the")
    w("entire project.\n")

    (DOCS / "REAL_RESULTS.md").write_text("\n".join(L) + "\n")
    print(f"wrote {DOCS / 'REAL_RESULTS.md'} ({len(L)} lines)")


if __name__ == "__main__":
    main()
